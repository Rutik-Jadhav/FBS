r = 20
l = 50 
b = 40


circle_area = (3.14 * r**2)/2

reactangle_area = l*b

total_area = circle_area + reactangle_area

barbed_wire = total_area*5

total_barbed_cost = barbed_wire * 35

print(f'circle area is {circle_area}.')
print(f'reactangle area is {reactangle_area}.')
print(f'total area is {total_area}.')
print(f'barbed wire in meter is {barbed_wire}.')
print(f'total barbed cost is{total_barbed_cost}.')